// Extracts the canonical CSS and the documentation data from spec/DESIGN_SYSTEM.md.
// The spec is the single source of truth: tokens, base CSS and component blueprints are
// copied verbatim (in document order) into src/generated/ds.css, and the token / text-style /
// section tables are exported to src/generated/spec.json for the documentation pages.
//
// Forced-state mirrors: every rule using :hover / :focus-visible / :focus-within / :active gets a
// twin selector using .is-hover / .is-focus-visible / .is-active, so the showcase can display
// hover and focus states statically without a pointer or keyboard.
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const root = path.resolve(import.meta.dirname, '..');
const specPath = path.join(root, 'spec', 'DESIGN_SYSTEM.md');
const doc = fs.readFileSync(specPath, 'utf8').split('\r\n').join('\n');
const outDir = path.join(root, 'src', 'generated');
fs.mkdirSync(outDir, { recursive: true });

// ── Sections ────────────────────────────────────────────────────────
const lines = doc.split('\n');
const headings = [];
let inFence = false;
lines.forEach((l, i) => {
  if (l.startsWith('```')) inFence = !inFence;
  if (inFence) return;
  const m = /^(#{2,4}) (.+)$/.exec(l);
  if (m) headings.push({ level: m[1].length, title: m[2].trim(), line: i });
});
const sections = headings.map((h, idx) => {
  let end = lines.length;
  for (let j = idx + 1; j < headings.length; j++) if (headings[j].level <= h.level) { end = headings[j].line; break; }
  const num = /^(\d+(?:\.\d+)?)\s/.exec(h.title)?.[1] ?? null;
  return { id: num ?? h.title, num, level: h.level, title: h.title, line: h.line + 1, body: lines.slice(h.line + 1, end).join('\n').trim() };
});

// ── CSS blocks ──────────────────────────────────────────────────────
const blocks = [];
const fence = /```css\n([\s\S]*?)```/g;
let m;
while ((m = fence.exec(doc))) {
  const line = doc.slice(0, m.index).split('\n').length;
  const owner = [...headings].reverse().find(h => h.line < line);
  blocks.push({ css: m[1], line, section: owner ? owner.title : '' });
}
const imports = [];
let css = '';
// §2.13's [data-density] block has the same specificity as §3's :root and appears earlier in the document, so in spec
// order :root would always win and comfortable mode would never apply (finding F-17). Emit it right after :root.
const ordered = [...blocks];
const dIdx = ordered.findIndex(b => b.css.includes('[data-density='));
const rIdx = ordered.findIndex(b => b.css.includes(':root {'));
if (dIdx >= 0 && rIdx > dIdx) { const [d] = ordered.splice(dIdx, 1); ordered.splice(rIdx, 0, d); }
for (const b of ordered) {
  const body = b.css.replace(/^@import url\([^)]*\);\s*$/gm, s => { imports.push(s.trim()); return ''; });
  css += `\n/* ── spec line ${b.line} · ${b.section.replace(/\*\//g, '')} ── */\n${body}`;
}

const stateMap = [
  [/:hover/g, '.is-hover'],
  [/:focus-visible/g, '.is-focus-visible'],
  [/:focus-within/g, '.is-focus-visible'],
  [/:active/g, '.is-active'],
];
// Light theme (spec/DESIGN_SYSTEM_LIGHT.md): its CSS blocks follow the dark system, so [data-theme="light"] overrides win
const lightPath = path.join(root, 'spec', 'DESIGN_SYSTEM_LIGHT.md');
if (fs.existsSync(lightPath)) {
  const light = fs.readFileSync(lightPath, 'utf8').split('\r\n').join('\n');
  for (const lm of light.matchAll(/```css\n([\s\S]*?)```/g)) {
    const line = light.slice(0, lm.index).split('\n').length;
    css += `\n/* ── light spec line ${line} ── */\n${lm[1]}`;
  }
}
const ast = postcss.parse(css);
let mirrored = 0;
ast.walkRules(rule => {
  if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  const extra = [];
  for (const sel of rule.selectors) {
    if (/:not\(:focus-visible\)/.test(sel)) continue;
    let s = sel;
    for (const [rx, cls] of stateMap) s = s.replace(rx, cls);
    if (s !== sel) extra.push(s);
  }
  if (extra.length) { rule.selectors = [...rule.selectors, ...extra]; mirrored++; }
});
const header = `/* GENERATED by scripts/extract-spec.mjs from spec/DESIGN_SYSTEM.md — do not edit.\n   ${blocks.length} css blocks, ${mirrored} rules mirrored to .is-hover/.is-focus-visible/.is-active. */\n`;
fs.writeFileSync(path.join(outDir, 'ds.css'), [...new Set(imports)].join('\n') + '\n' + header + ast.toString());

// ── Tables ──────────────────────────────────────────────────────────
function tablesIn(text) {
  const out = [];
  const ls = text.split('\n');
  for (let i = 0; i < ls.length; i++) {
    if (/^\|/.test(ls[i]) && /^\|[-| :]+\|$/.test(ls[i + 1] ?? '')) {
      const head = cells(ls[i]);
      const rows = [];
      let j = i + 2;
      while (j < ls.length && /^\|/.test(ls[j])) { rows.push(cells(ls[j])); j++; }
      out.push({ head, rows });
      i = j;
    }
  }
  return out;
}
function cells(l) {
  return l.replace(/^\|/, '').replace(/\|$/, '').split(/(?<!\\)\|/).map(c => c.trim());
}
const strip = s => s.replace(/`/g, '').replace(/\*\*/g, '').trim();

// Tokens declared in :root (authoritative values)
const rootBlock = /:root \{([\s\S]*?)\n\}/.exec(blocks.find(b => b.css.includes(':root {'))?.css ?? '')?.[1] ?? '';
const declared = {};
const declaredGroup = {};
let group = 'Other';
for (const l of rootBlock.split('\n')) {
  const g = /\/\* ── ([^─]+?) ─/.exec(l) ?? /^\s*\/\* (Focus)/.exec(l);
  if (g && !/--ds-/.test(l)) group = g[1].trim();
  for (const d of l.matchAll(/(--ds-[a-z0-9-]+)\s*:\s*([^;]+);/g)) { declared[d[1]] = d[2].trim(); declaredGroup[d[1]] = group; }
}

// Light-only tokens (declared only under [data-theme="light"], used only by light rules) count as declared too
const lightBlock = /\[data-theme="light"\] \{([\s\S]*?)\n\}/.exec(css)?.[1] ?? '';
for (const d of lightBlock.matchAll(/(--ds-[a-z0-9-]+)\s*:\s*([^;]+);/g)) if (!(d[1] in declared)) { declared[d[1]] = d[2].trim(); declaredGroup[d[1]] = 'Light theme only'; }

// Documented token rows (any table whose first column is a --ds- token), with the section they live in
const tokenDocs = {};
for (const sec of sections.filter(s => s.num && /^2\./.test(s.num) || /^(Backgrounds|Text|Borders|Brand|Status|Overlays|Neutrals|Text neutrals|Brand blue|Categorical|Semantic spacing|Font family|Type scale)/.test(s.title))) {
  for (const t of tablesIn(sec.body)) {
    for (const r of t.rows) {
      const name = strip(r[0]);
      if (!/^--ds-/.test(name)) continue;
      tokenDocs[name] ??= { section: sec.title, value: strip(r[1] ?? ''), use: strip(r.slice(2).join(' · ')) };
    }
  }
}

// Primitive reference labels (§2.1)
const primitives = [];
const prim = sections.find(s => s.num === '2.1');
for (const sub of sections.filter(s => s.line > prim.line && s.level === 4 && s.line < sections.find(x => x.num === '2.2').line)) {
  for (const t of tablesIn(sub.body)) for (const r of t.rows) primitives.push({ group: sub.title, name: strip(r[0]), value: strip(r[1]), use: strip(r[2] ?? '') });
}

// Named text styles (§2.3)
const textStyles = [];
const typo = sections.find(s => s.title.startsWith('Named text styles'));
for (const t of tablesIn(typo.body)) for (const r of t.rows) {
  if (r.length < 9) continue;
  textStyles.push({ name: strip(r[0]), family: strip(r[1]), size: strip(r[2]), weight: strip(r[3]), lineHeight: strip(r[4]), tracking: strip(r[5]), transform: strip(r[6]), color: strip(r[7]), usage: strip(r[8]) });
}

// Utility classes for every named text style: .ds-ts-<name> (derived from the §2.3 table)
const px = v => (/^\d+(\.\d+)?px$/.test(v) ? v : /^1 \(12px\)$/.test(v) ? '1' : null);
let tsCss = '/* GENERATED from the §2.3 "Named text styles" table — do not edit. */\n';
for (const t of textStyles) {
  const decl = [`font-family: var(--ds-font-family)`];
  if (px(t.size)) decl.push(`font-size: ${t.size}`);
  const w = /^(\d{3})/.exec(t.weight)?.[1]; if (w) decl.push(`font-weight: ${w}`);
  const lh = px(t.lineHeight); if (lh) decl.push(`line-height: ${lh}`);
  const tr = /^([+-]?\d+(\.\d+)?)px/.exec(t.tracking)?.[1]; if (tr) decl.push(`letter-spacing: ${tr.replace('+', '')}px`);
  if (t.transform === 'UPPERCASE') decl.push('text-transform: uppercase');
  const c = t.color.split(/[ +]/)[0];
  const cTok = c === 'white' ? '--ds-color-text-primary' : ['--ds-color-' + c, '--ds-' + c].find(n => n in declared);
  if (cTok) decl.push(`color: var(${cTok})`);
  tsCss += `.ds-ts-${t.name} { ${decl.join('; ')}; }\n`;
}
fs.writeFileSync(path.join(outDir, 'text-styles.css'), tsCss);

// Asset registry (§2.11-B): illustration rows, plus the Figma crop table (image-fill transforms)
const registry = [];
const crops = [];
const reg = sections.find(s => s.title.startsWith('B. Asset registry'));
for (const t of tablesIn(reg.body)) for (const r of t.rows) {
  if (/^Crop id$/i.test(strip(t.head[0] ?? ''))) { crops.push({ id: strip(r[0]), asset: strip(r[1]), w: strip(r[2]), h: strip(r[3]), l: strip(r[4]), t: strip(r[5]), where: strip(r[6] ?? '') }); continue; }
  if (r.length < 7 || !/\.(png|jpe?g|webp|svg)$/i.test(strip(r[3]))) continue;
  const nm = /^(\S+)(?:\s*\((.*)\))?/.exec(strip(r[0]));
  const fr = /(\d+) frames|sprite, (\d+)/.exec(nm[2] ?? '');
  registry.push({ name: nm[1], note: nm[2] ?? '', frames: fr ? +(fr[1] ?? fr[2]) : 0, depicts: strip(r[1]), purpose: strip(r[2]), file: strip(r[3]), master: strip(r[4]), display: strip(r[5]), fallback: strip(r[6]) });
}

// Decisions (§15.1) and resolution log ids (§11)
const decisions = [];
const dec = sections.find(s => s.num === '15.1');
for (const t of tablesIn(dec.body)) for (const r of t.rows) decisions.push({ id: strip(r[0]), decision: strip(r[1]), recommendation: strip(r[2]), ref: strip(r[3]) });

const spec = {
  generatedFrom: 'spec/DESIGN_SYSTEM.md',
  lineCount: lines.length,
  cssBlocks: blocks.map(b => ({ line: b.line, section: b.section, css: b.css })),
  sections: sections.map(({ id, num, level, title, line, body }) => ({ id, num, level, title, line, body })),
  declared,
  declaredGroup,
  tokenDocs,
  primitives,
  textStyles,
  registry,
  crops,
  decisions,
};
fs.writeFileSync(path.join(outDir, 'spec.json'), JSON.stringify(spec));
console.log(`spec: ${sections.length} sections, ${blocks.length} css blocks (${mirrored} state-mirrored rules), ${Object.keys(declared).length} tokens, ${textStyles.length} text styles, ${registry.length} assets, ${crops.length} crops, ${primitives.length} primitives`);
