let out = `/* GENERATED by scripts/build-figma-icons.mjs from public/figma/icons — do not edit.
   Exact Figma path data; baked colors replaced by currentColor. Typed as LucideIcon so every component that
   takes a Lucide glyph (Icon, Button leading/trailing, IconButton) accepts these too. */
import { createElement, forwardRef } from 'react';
import type { LucideIcon, LucideProps } from 'lucide-react';

function make(name: string, w: number, h: number, viewBox: string, inner: string): LucideIcon {
  const C = forwardRef<SVGSVGElement, LucideProps>(({ size, color, strokeWidth: _s, absoluteStrokeWidth: _a, style, ...rest }, ref) => {
    const scale = size === undefined ? 1 : Number(size) / Math.max(w, h);
    return createElement('svg', { ref, width: +(w * scale).toFixed(3), height: +(h * scale).toFixed(3), viewBox, fill: 'none',
      style: color ? { ...style, color } : style, ...rest, dangerouslySetInnerHTML: { __html: inner } });
  });
  C.displayName = name;
  return C as unknown as LucideIcon;
}
`;
const meta = [];
for (const [name, [file, layer]] of Object.entries(MAP)) {
  const svg = fs.readFileSync(path.join(dir, file), 'utf8');
  const w = +/width="([\d.]+)"/.exec(svg)[1];
  const h = +/height="([\d.]+)"/.exec(svg)[1];
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s(id)="[^"]*"/g, '')
    .replace(/(stroke|fill)="(?!none)[^"]*"/g, '$1="currentColor"')
    .replace(/\s+/g, ' ').trim();
  out += `export const ${name} = make('${name}', ${w}, ${h}, '${viewBox}', ${JSON.stringify(inner)});\n`;
  meta.push(`  { name: '${name}', file: '${file}', layer: ${JSON.stringify(layer)}, w: ${w}, h: ${h} },`);
}
out += `\n/** Source of every icon above (Iconography page and QA). */\nexport const FIGMA_ICONS = [\n${meta.join('\n')}\n] as const;\n`;
fs.writeFileSync(path.join(root, 'src/components/ds/figmaIcons.ts'), out);
console.log(`figma icons: ${Object.keys(MAP).length} written`);
